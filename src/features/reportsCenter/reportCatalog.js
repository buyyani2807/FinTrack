export function visibleReports(orgSettings = {}, access = {}) {
  return REPORT_CATALOG.filter(report => {
    if (!report.module) return true;
    if (report.module === "accounts") return Boolean(access.accounts) && isModuleEnabled(orgSettings, "accounts");
    if (report.module === "cashbook") return Boolean(access.cashbook);
    if (report.module === "daily") return Boolean(access.daily);
    if (report.module === "monthly") return Boolean(access.monthly);
    if (report.module === "chit") return Boolean(access.chit);
    return true;
  });
}

export function reportById(id) {
  return REPORT_CATALOG.find(report => report.id === id) || null;
}

